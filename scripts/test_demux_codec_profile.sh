#!/usr/bin/env bash
# Compile the codec profile the demuxers publish at file load
# (mp_codec_profile_from_extradata, patch 0204) and check it against the
# profile mpv publishes once the decoder has output a frame: the pinned
# FFmpeg's software H.264 and HEVC decoders decode the first access unit of
# each sample and mp_codec_info_from_av names their profile. A minimal host
# configure of the FFmpeg tree builds just those two decoders (no asm, no
# programs). Pass an already-patched mpv tree and an FFmpeg tree for offline
# use; otherwise fetch the pinned Android sources in a temporary directory.
#
# --regenerate rewrites test_demux_codec_profile_samples.h from fresh
# one-frame x264 and x265 encodes muxed into Matroska and MP4 (needs a host
# ffmpeg with libx264 and libx265); the committed header is what the test
# normally runs against.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
sources=()
regenerate=0
for arg in "$@"; do
    case "$arg" in
        --regenerate) regenerate=1 ;;
        *) sources+=("$arg") ;;
    esac
done
mpv_dir="${sources[0]:-}"
ffmpeg_dir="${sources[1]:-}"
workdir="$(mktemp -d)"
trap 'rm -rf "$workdir"' EXIT

if [[ $regenerate -eq 1 ]]; then
    python3 - "$workdir" "$root/scripts/test_demux_codec_profile_samples.h" <<'PY'
import json
import subprocess
import sys

work, out = sys.argv[1], sys.argv[2]
X265 = ["-c:v", "libx265", "-x265-params", "log-level=error:info=0"]
# x264 writes its options into an SEI; drop it to keep the samples small.
X264 = ["-c:v", "libx264", "-bsf:v", "filter_units=remove_types=6"]
# name, codec, the profile the encode is made to have, encoder arguments
STREAMS = [
    ("hevc_main", "hevc", "Main", X265 + ["-pix_fmt", "yuv420p"]),
    ("hevc_main10", "hevc", "Main 10", X265 + ["-pix_fmt", "yuv420p10le"]),
    ("hevc_rext", "hevc", "Rext", X265 + ["-pix_fmt", "yuv422p10le"]),
    ("h264_constrained_baseline", "h264", "Constrained Baseline",
     X264 + ["-pix_fmt", "yuv420p", "-profile:v", "baseline"]),
    ("h264_high", "h264", "High", X264 + ["-pix_fmt", "yuv420p", "-profile:v", "high"]),
    ("h264_high10", "h264", "High 10", X264 + ["-pix_fmt", "yuv420p10le", "-profile:v", "high10"]),
    ("h264_high10_intra", "h264", "High 10 Intra",
     X264 + ["-pix_fmt", "yuv420p10le", "-profile:v", "high10", "-x264-params", "keyint=1"]),
]


def hexdump(text):
    """Bytes of an ffprobe -show_data dump: 'offset: 8 groups of 4 hex  ascii'."""
    return b"".join(bytes.fromhex(line[10:49].replace(" ", ""))
                    for line in text.splitlines() if line.strip())


def probe(path, entries):
    result = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_data",
                             "-show_" + entries, "-of", "json", path],
                            capture_output=True, text=True, check=True)
    return json.loads(result.stdout)[entries]


def array(name, data):
    rows = ["    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ","
            for i in range(0, len(data), 12)]
    return "static const uint8_t %s[] = {\n%s\n};\n" % (name, "\n".join(rows))


arrays, table = [], []
for name, codec, profile, args in STREAMS:
    mkv, mp4 = f"{work}/{name}.mkv", f"{work}/{name}.mp4"
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi",
                    "-i", "color=c=gray:s=64x64:r=25", "-frames:v", "1", *args, mkv], check=True)
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", mkv,
                    "-c", "copy", mp4], check=True)
    packets = []
    for container, path in (("mkv", mkv), ("mp4", mp4)):
        stream = probe(path, "streams")[0]
        record = hexdump(stream["extradata"])
        if len(record) != stream["extradata_size"] or stream.get("profile") != profile:
            sys.exit(f"{name}.{container}: {len(record)}-byte record, host decoder says "
                     f"{stream.get('profile')!r}, want {stream['extradata_size']} bytes, {profile!r}")
        arrays.append(array(f"{name}_{container}", record))
        packets.append(hexdump(probe(path, "packets")[0]["data"]))
        table.append(f'    {{"{name}.{container}", "{codec}", "{profile}", '
                     f'{name}_{container}, sizeof({name}_{container}), '
                     f'{name}_packet, sizeof({name}_packet)}},')
    if packets[0] != packets[1]:
        sys.exit(f"{name}: Matroska and MP4 carry different first access units")
    arrays.append(array(f"{name}_packet", packets[0]))

with open(out, "w") as f:
    f.write("// One-frame 64x64 x264 and x265 encodes, each muxed into Matroska and MP4 by\n"
            "// the host ffmpeg: the decoder configuration record each container carries\n"
            "// (CodecPrivate, stsd avcC/hvcC) and the first access unit, which both\n"
            "// carry alike. Generated by test_demux_codec_profile.sh --regenerate.\n\n")
    f.write("\n".join(arrays))
    f.write("\nstruct sample {\n    const char *name, *codec, *profile;\n"
            "    const uint8_t *record;\n    int record_size;\n"
            "    const uint8_t *packet;\n    int packet_size;\n};\n\n"
            "static const struct sample samples[] = {\n" + "\n".join(table) + "\n};\n")
PY
    echo "regenerated $(grep -c '^    {"' "$root/scripts/test_demux_codec_profile_samples.h") samples"
fi

# The pin contract lives in scripts/patches.py: it resolves the
# override-aware pin, clones the ref, proves HEAD is the pinned commit and
# applies the resolved android series (0204 is in series.common).
if [[ -z "$mpv_dir" ]]; then
    mpv_dir="$workdir/mpv"
    (cd "$root" && python3 scripts/patches.py fetch-pinned mpv android "$mpv_dir")
fi
if [[ -z "$ffmpeg_dir" ]]; then
    ffmpeg_dir="$workdir/ffmpeg"
    (cd "$root" && python3 scripts/patches.py fetch-pinned ffmpeg android "$ffmpeg_dir")
fi
ffmpeg_dir="$(cd "$ffmpeg_dir" && pwd)"

# The profile the demuxers publish at load, and the one mpv's decoder wrapper
# publishes in its place once the decoder has output a frame.
inc="$workdir/codec_profile.inc"
python3 "$root/scripts/extract.py" symbol "$mpv_dir/common/av_common.c" "$inc" \
    --fn mp_codec_profile_from_extradata --return 'const char *'
python3 "$root/scripts/extract.py" symbol "$mpv_dir/common/av_common.c" "$inc" --append \
    --fn mp_codec_info_from_av --return void

build="$workdir/build"
mkdir -p "$build"
(cd "$build" && "$ffmpeg_dir/configure" --disable-everything --disable-programs --disable-doc \
    --disable-network --disable-autodetect --disable-asm \
    --enable-decoder=h264 --enable-decoder=hevc >"$workdir/configure.log" 2>&1) \
    || { cat "$workdir/configure.log"; exit 1; }
make -C "$build" -j"$(getconf _NPROCESSORS_ONLN)" libavcodec/libavcodec.a libavutil/libavutil.a \
    >"$workdir/make.log" 2>&1 || { tail -50 "$workdir/make.log"; exit 1; }

cc -O2 -std=c11 -Wall -Wextra -Werror -Wno-unused-parameter \
    -I"$workdir" -I"$root/scripts" -I"$build" -I"$ffmpeg_dir" \
    -o "$workdir/test" "$root/scripts/test_demux_codec_profile.c" \
    "$build/libavcodec/libavcodec.a" "$build/libavutil/libavutil.a" -lm -lpthread
"$workdir/test"
